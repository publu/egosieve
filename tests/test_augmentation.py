def test_group_cannot_cross_preassigned_splits(tmp_path: Path) -> None:
    _make_source(tmp_path / "videos" / "source.mp4")
    records = []
    for index, split in enumerate(("train", "test")):
        records.append(
            {
                "schema": SCHEMA_VERSION,
                "id": f"source-{index}",
                "group_id": "shared-session",
                "video": "videos/source.mp4",
                "license": "CC0-1.0",
                "split": split,
                "windows": [{"start_s": 0.0, "end_s": 1.0}],
            }
        )
    annotations = tmp_path / "source.jsonl"
    annotations.write_text(
        "".join(json.dumps(record) + "\n" for record in records),
        encoding="utf-8",
    )
    with pytest.raises(AugmentationError, match="crosses source splits"):
        build_augmented_corpus(
            annotations,
            tmp_path / "derived",
            allowed_licenses=["CC0-1.0"],
            config=AugmentationConfig(transforms=("blur",)),
            ffmpeg_bin=str(FFMPEG),
            ffprobe_bin=str(FFPROBE),
        )
